/** Deterministic "message of the day" so it stays the same all day. */
export function messageOfTheDay(dateISO: string): string {
  let hash = 0;
  for (const ch of dateISO) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return AHMED_MESSAGES[hash % AHMED_MESSAGES.length];
}

export function randomMessage(exclude?: string): string {
  if (AHMED_MESSAGES.length < 2) return AHMED_MESSAGES[0];
  let m: string;
  do m = AHMED_MESSAGES[Math.floor(Math.random() * AHMED_MESSAGES.length)];
  while (m === exclude);
  return m;
}
