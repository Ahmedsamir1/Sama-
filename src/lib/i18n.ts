export function formatDate(iso: string, lang: Language, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long' }): string {
  const [y, m, d] = iso.split('-').map(Number);
  return new Intl.DateTimeFormat(DICTS[lang].locale, opts).format(new Date(y, m - 1, d));
}

export function greetingFor(hour: number, t: Dict): string {
  if (hour >= 4 && hour < 13) return t.greetingMorning;
  if (hour >= 13 && hour < 22) return t.greetingEvening;
  return t.greetingNight;
}
